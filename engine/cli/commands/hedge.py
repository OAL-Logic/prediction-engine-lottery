"""
Hedge Command ⚖️
==============
Generates a mathematically balanced combinatorial hedge portfolio.
Splits the budget into an aggressive Jackpot Core and a conservative,
covering Hedge Foundation to offset potential stake losses.
"""

from __future__ import annotations

from typing import Annotated

import typer
from rich.console import Console
from rich.panel import Panel
from rich.table import Table

from engine.cli.utils import get_adapter
from engine.modules.hedging import CombinatorialHedger
from engine.strategies import get_strategy

console = Console()


def hedge(
    lottery: Annotated[str, typer.Argument(help="Lottery name")],
    budget: Annotated[float, typer.Option("--budget", "-b", help="Total budget for this hedged bet")] = 100.0,
    risk_profile: Annotated[str, typer.Option("--risk", "-r", help="conservative | balanced | aggressive")] = "balanced",
) -> None:
    """🛡️ Generate an optimized 'Hedge Portfolio' to balance risk and maximize returns.

    Splits your budget into:
      1. Jackpot Core: Focused, high-EV numbers generated by deep learning (GNN) strategies.
      2. Hedge Foundation: A covering design (abbreviated wheel) targeting lower-tier prizes.

    Args:
        lottery: Lottery identifier (e.g. 'br/lotofacil')
        budget:  Total money to spend on tickets
        risk_profile: 'conservative' | 'balanced' | 'aggressive'

    Example:
        lottery serve br/lotofacil --budget 100.0 --risk balanced
    """
    adapter = get_adapter(lottery)
    df = adapter.fetch()
    rules = adapter.rules
    price = rules.ticket_price

    if budget < price:
        console.print(f"[red]Error: Budget {budget} is less than the ticket price {price}.[/red]")
        raise typer.Exit(1)

    console.rule(f"[bold cyan]⚖️ Combinatorial Hedging & Portfolio Balance: {rules.name}[/bold cyan]")
    console.print(f"  [dim]Budget: {budget:.2f} {rules.currency} | Risk Profile: {risk_profile.upper()}[/dim]\n")

    # 1. Compute strategy scores for Jackpot and Hedge pools
    with console.status("[bold green]Running Graph Neural Network & stability checks…"):
        # For Jackpot Core, we try to load the GNN deep strategy, falling back to markov_regime
        try:
            jackpot_strat = get_strategy("gnn")
        except Exception:
            jackpot_strat = get_strategy("markov_regime")
            
        # For Hedge Foundation, we load the hedge or weighted strategy
        try:
            hedge_strat = get_strategy("hedge")
        except Exception:
            hedge_strat = get_strategy("weighted")

        j_scores = jackpot_strat.score(df, rules)
        h_scores = hedge_strat.score(df, rules)

    # 2. Generate balanced portfolio using CombinatorialHedger
    hedger = CombinatorialHedger(rules)
    portfolio = hedger.generate_balanced_portfolio(
        j_scores, h_scores, budget, risk_profile
    )

    # 3. Simulate and prove the hedge mathematically via Monte Carlo
    with console.status("[bold green]Running Monte Carlo payout simulations (5,000 trials)…"):
        metrics = hedger.simulate_portfolio_payouts(portfolio, trials=5000)

    # 4. Display Portfolio allocations
    table = Table(title="[bold]Portfolio Allocations[/bold]", box=None)
    table.add_column("Type", style="bold cyan")
    table.add_column("Tickets Count", justify="right")
    table.add_column("Allocation", justify="right", style="green")
    table.add_column("Pool Numbers", style="dim")

    table.add_row(
        "Jackpot Core (GNN/Markov)",
        str(portfolio["jackpot_count"]),
        f"{portfolio['jackpot_allocation']:.2f} {rules.currency}",
        str(portfolio["jackpot_pool"][:10]) + "..."
    )
    if portfolio["hedge_count"] > 0:
        table.add_row(
            "Hedge Foundation (Abbrev. Wheel)",
            str(portfolio["hedge_count"]),
            f"{portfolio['hedge_allocation']:.2f} {rules.currency}",
            str(portfolio["hedge_pool"])
        )

    console.print(table)
    console.print()

    # 5. Display generated tickets
    t_table = Table(title="[bold]Allocated Bet Slips[/bold]", box=None)
    t_table.add_column("#", justify="right", style="dim")
    t_table.add_column("Numbers", style="bold green")
    t_table.add_column("Role", style="bold yellow")

    idx = 1
    for t in portfolio["jackpot_tickets"]:
        t_table.add_row(str(idx), str(t), "🎯 JACKPOT CORE")
        idx += 1
    for t in portfolio["hedge_tickets"]:
        t_table.add_row(str(idx), str(t), "🛡️ HEDGE FOUNDATION")
        idx += 1

    console.print(t_table)
    console.print()

    # 6. Display Mathematical Hedge Proof Panel
    proof_content = (
        f"🎯 [bold]Win Probability[/bold]: [green]{metrics.win_probability}%[/green] (chance of hitting >= 1 prize tier)\n"
        f"🛡️ [bold]Hedge Coverage Ratio[/bold]: [cyan]{metrics.hedge_coverage_ratio * 100:.1f}%[/cyan] (expected return coverage)\n"
        f"♻️ [bold]Self-Sustainability (100% Free Roll)[/bold]: [green]{metrics.self_sustainability_score}%[/green] probability\n"
        f"💰 [bold]Expected Payout[/bold]: [bold yellow]{metrics.expected_payout:.2f} {rules.currency}[/bold yellow] per draw\n"
        f"📊 [bold]Net Portfolio ROI[/bold]: [{'green' if metrics.net_roi >= 0 else 'red'}]{metrics.net_roi}%[/{'green' if metrics.net_roi >= 0 else 'red'}]\n"
        f"📉 [bold]Maximum Simulated Drawdown[/bold]: [red]{metrics.max_drawdown:.2f} {rules.currency}[/red]\n"
    )

    console.print(Panel(proof_content, title="✨ MATHEMATICAL HEDGE PROOF", border_style="cyan"))
