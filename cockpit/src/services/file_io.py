"""
File I/O & Profile Synchronization Service
==========================================
Provides comprehensive import/export routines for:
1. SamLotto SYLK files (.slk)
2. Space-delimited & CSV ticket files (.txt, .csv)
3. Bi-directional Desktop JSON profiles <-> Headless Engine YAML specs
"""

from __future__ import annotations

import os
import re
import csv
import json
from pathlib import Path
from typing import List, Dict, Any, Optional, Tuple

import yaml
from cockpit.src.core.models import (
    ProfileBundle,
    FilterNode,
    ToleranceRule,
    ToleranceMode,
    WheelingConfig,
    WheelType,
)


class TicketFileIO:
    """
    Parses and serializes lottery tickets across multiple industry formats:
    - SamLotto .slk (SYLK / Symbolic Link format)
    - SamLotto .txt (Space-delimited zero-padded numbers: "01 03 07 12 15 25")
    - Standard .csv (Comma-delimited with or without headers)
    - Plain text (one combination per line)
    """

    @staticmethod
    def parse_tickets(filepath_or_content: str) -> List[List[int]]:
        """
        Intelligently parses tickets from a filepath or raw string buffer.
        Detects SLK, CSV, or whitespace-delimited formats.
        """
        # Determine if input is a filepath or raw text
        raw_text = filepath_or_content
        if "\n" not in filepath_or_content and os.path.exists(filepath_or_content):
            with open(filepath_or_content, "r", encoding="utf-8", errors="replace") as f:
                raw_text = f.read()

        lines = [line.strip() for line in raw_text.splitlines() if line.strip()]
        if not lines:
            return []

        # Check for SYLK / SLK format
        if lines[0].startswith("ID;") or any(l.startswith("C;X") for l in lines[:10]):
            return TicketFileIO._parse_slk(lines)

        # Otherwise, parse line by line (supports CSV or space/tab-separated numbers)
        tickets: List[List[int]] = []
        for line in lines:
            # Skip comment or header lines
            if line.startswith("#") or line.startswith("//") or line.lower().startswith("game") or line.lower().startswith("draw"):
                continue

            # Extract all integers on this line
            numbers = [int(tok) for tok in re.findall(r"\b\d+\b", line)]
            if len(numbers) >= 2:
                # Deduplicate and sort ticket balls
                clean_ticket = sorted(list(dict.fromkeys(numbers)))
                tickets.append(clean_ticket)

        return tickets

    @staticmethod
    def _parse_slk(lines: List[str]) -> List[List[int]]:
        """
        Parses Microsoft SYLK (.slk) format commonly generated by SamLotto.
        SYLK cells are represented as:
          C;X{col};Y{row};K{value}
        or
          C;Y{row};X{col};K"{value}"
        """
        grid: Dict[int, Dict[int, int]] = {}
        row_max = 0

        for line in lines:
            if not line.startswith("C;"):
                continue

            # Match X (col), Y (row), K (value)
            parts = line[2:].split(";")
            row = None
            col = None
            val = None

            for part in parts:
                if part.startswith("Y"):
                    try:
                        row = int(part[1:])
                    except ValueError:
                        pass
                elif part.startswith("X"):
                    try:
                        col = int(part[1:])
                    except ValueError:
                        pass
                elif part.startswith("K"):
                    v_str = part[1:].strip('"\'')
                    try:
                        val = int(v_str)
                    except ValueError:
                        pass

            if row is not None and col is not None and val is not None:
                if row not in grid:
                    grid[row] = {}
                grid[row][col] = val
                if row > row_max:
                    row_max = row

        tickets: List[List[int]] = []
        for r in range(1, row_max + 1):
            if r in grid:
                row_dict = grid[r]
                cols_sorted = sorted(row_dict.keys())
                ticket = [row_dict[c] for c in cols_sorted]
                if len(ticket) >= 2:
                    tickets.append(sorted(ticket))

        return tickets

    @staticmethod
    def export_tickets_txt(
        tickets: List[List[int]],
        filepath: str,
        zero_padded: bool = True,
        delimiter: str = " ",
    ) -> None:
        """
        Exports tickets as space-delimited text (SamLotto compatible).
        Example:
          01 04 07 12 15 25
          02 05 08 14 19 23
        """
        lines = []
        fmt = "{:02d}" if zero_padded else "{:d}"
        for t in tickets:
            line = delimiter.join(fmt.format(num) for num in sorted(t))
            lines.append(line)

        with open(filepath, "w", encoding="utf-8") as f:
            f.write("\n".join(lines) + "\n")

    @staticmethod
    def export_tickets_csv(tickets: List[List[int]], filepath: str, header: bool = False) -> None:
        """Exports tickets as standard comma-separated values."""
        with open(filepath, "w", encoding="utf-8", newline="") as f:
            writer = csv.writer(f)
            if header and tickets:
                max_len = max(len(t) for t in tickets)
                writer.writerow([f"Ball_{i+1}" for i in range(max_len)])
            for t in tickets:
                writer.writerow(sorted(t))

    @staticmethod
    def export_tickets_slk(tickets: List[List[int]], filepath: str) -> None:
        """
        Exports tickets as standard SamLotto SYLK (.slk) spreadsheet file.
        Header:
          ID;P
          B;Y{rows};X{cols}
        Body:
          C;X{col};Y{row};K{val}
        Footer:
          E
        """
        if not tickets:
            return

        rows = len(tickets)
        cols = max(len(t) for t in tickets)

        lines = [
            "ID;PWXL;N;E",
            f"B;Y{rows};X{cols};D0 0 {rows} {cols}",
        ]

        for r_idx, t in enumerate(tickets, start=1):
            sorted_t = sorted(t)
            for c_idx, val in enumerate(sorted_t, start=1):
                lines.append(f"C;X{c_idx};Y{r_idx};K{val}")

        lines.append("E")

        with open(filepath, "w", encoding="utf-8") as f:
            f.write("\n".join(lines) + "\n")


class ProfileManager:
    """
    Manages loading, saving, and format translation between:
    - Native Desktop Profile JSON (.json)
    - Headless Engine CLI YAML (.yaml)
    """

    @staticmethod
    def save_profile_json(profile: ProfileBundle, filepath: str) -> None:
        """Saves a ProfileBundle to JSON."""
        with open(filepath, "w", encoding="utf-8") as f:
            f.write(profile.to_json())

    @staticmethod
    def load_profile_json(filepath: str) -> ProfileBundle:
        """Loads a ProfileBundle from JSON."""
        with open(filepath, "r", encoding="utf-8") as f:
            return ProfileBundle.from_json(f.read())

    @staticmethod
    def save_profile_yaml(profile: ProfileBundle, filepath: str) -> None:
        """Exports a ProfileBundle to CLI-compatible YAML."""
        with open(filepath, "w", encoding="utf-8") as f:
            f.write(profile.to_cli_yaml())

    @staticmethod
    def load_profile_yaml(filepath: str) -> ProfileBundle:
        """
        Imports a CLI YAML profile (e.g. lotofacil_optimized.yaml)
        and converts it into a hydrated ProfileBundle for Cockpit.
        """
        with open(filepath, "r", encoding="utf-8") as f:
            data = yaml.safe_load(f) or {}

        game_id = data.get("game", "br/lotofacil")
        strat_weights = data.get("strategies", {})

        # Parse tolerance
        tol_data = data.get("tolerance", {})
        mode_str = tol_data.get("mode", "AND")
        try:
            mode = ToleranceMode(mode_str)
        except ValueError:
            mode = ToleranceMode.AND

        tolerance = ToleranceRule(
            mode=mode,
            min_pass=tol_data.get("min_pass", 0),
            max_pass=tol_data.get("max_pass", 10),
        )

        # Parse wheeling
        wheel_data = data.get("wheeling", {})
        wheeling = WheelingConfig(
            guarantee=wheel_data.get("guarantee", 13),
            condition_match=wheel_data.get("condition_match", 15),
            pruning_enabled=wheel_data.get("pruning", True),
        )

        # Parse filters
        filter_dict = data.get("filters", {})
        filter_nodes = []
        for fid, bounds in filter_dict.items():
            filter_nodes.append(
                FilterNode(
                    id=fid,
                    name=fid.replace("_", " ").title(),
                    category="CLI Import",
                    enabled=True,
                    min_val=float(bounds.get("min", 0)),
                    max_val=float(bounds.get("max", 100)),
                )
            )

        return ProfileBundle(
            active_game_id=game_id,
            active_perspective="Studio",
            tolerance=tolerance,
            wheeling=wheeling,
            filters=filter_nodes,
            strategy_weights=strat_weights,
        )
